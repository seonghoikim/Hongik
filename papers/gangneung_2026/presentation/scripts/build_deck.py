def table(s, x, y, w, rows, widths, size=10, hl=()):
    t = s.shapes.add_table(len(rows), len(rows[0]), Inches(x), Inches(y), Inches(w),
                           Inches(0.32 * len(rows))).table
    for c, cw in enumerate(widths):
        t.columns[c].width = Inches(cw)
    for r, row in enumerate(rows):
        for c, v in enumerate(row):
            cell = t.cell(r, c)
            cell.text = v
            run = cell.text_frame.paragraphs[0].runs[0]
            run.font.size, run.font.name, run.font.bold = Pt(size), FONT, r == 0
            cell.fill.solid()
            cell.fill.fore_color.rgb = rgb("44536A") if r == 0 else rgb("FFFFFF")
            run.font.color.rgb = rgb("FFFFFF") if r == 0 else (RED if (r, c) in hl else INK)


