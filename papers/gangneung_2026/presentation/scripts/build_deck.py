def fig_left(prs, head, figpath, items, note, cap=None, split=0.58, size=13):
    """김장환 자료의 기본형: 왼쪽 그림, 오른쪽 글머리표."""
    s = blank(prs)
    header(s, head)
    fw = 9.2 * split
    picture(s, figpath, 0.35, 0.85, fw, 4.0 if cap else 4.25)
    if cap:
        caption(s, cap, 0.35, 4.88, fw)
    text(s, 0.45 + fw, 0.95, 9.55 - fw - 0.45, 4.15, bullets(items, size), size=size, spacing=1.15)
    notes(s, note)
    return s


def fig_full(prs, head, figpath, note, items=None, cap=None, size=12):
    """그림 전체 폭 + 아래 한 줄 요약."""
    s = blank(prs)
    header(s, head)
    h = 3.55 if items else 4.15
    picture(s, figpath, 0.35, 0.8, 9.3, h)
    y = 0.8 + h + 0.05
    if cap:
        caption(s, cap, 0.35, y, 9.3)
        y += 0.25
    if items:
        text(s, 0.5, y, 9.0, 5.15 - y, bullets(items, size), size=size, spacing=1.05)
    notes(s, note)
    return s


